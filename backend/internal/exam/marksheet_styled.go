package exam

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
	"time"
)

type markSheetRow struct {
	Roll  string
	Name  string
	Marks int
}

func pdfASCII(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r < 32 || r > 126 {
			b.WriteByte('?')
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}
func pdfEscape(s string) string {
	s = pdfASCII(s)
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, "(", `\(`)
	s = strings.ReplaceAll(s, ")", `\)`)
	return s
}
func pdfText(b *strings.Builder, font int, size int, x, y int, s string) {
	fmt.Fprintf(b, "BT /F%d %d Tf 1 0 0 1 %d %d Tm (%s) Tj ET\n", font, size, x, y, pdfEscape(s))
}
func pdfFill(b *strings.Builder, rgb string, x, y, w, h int) {
	fmt.Fprintf(b, "%s rg %d %d %d %d re f\n", rgb, x, y, w, h)
}
func pdfLine(b *strings.Builder, rgb string, x1, y1, x2, y2 int) {
	fmt.Fprintf(b, "%s RG 0.7 w %d %d m %d %d l S\n", rgb, x1, y1, x2, y2)
}
func truncateASCII(s string, width int) string {
	s = pdfASCII(s)
	if len(s) <= width {
		return s
	}
	if width < 4 {
		return s[:width]
	}
	return s[:width-3] + "..."
}

// Styled A4 marksheet. All drawing uses PDF vector primitives, no external font/logo dependency.
// Helvetica standard fonts display ASCII only; Unicode font embedding can be added later.
func buildStyledMarksPDF(courseName, courseCode, teacherName, examTitle string, records []markSheetRow, max int) []byte {
	const pageW, pageH = 595, 842
	const perPage = 29
	if strings.TrimSpace(courseCode) == "" {
		courseCode = "Not assigned"
	}
	if strings.TrimSpace(courseName) == "" {
		courseName = "Untitled classroom"
	}
	if strings.TrimSpace(teacherName) == "" {
		teacherName = "Class teacher"
	}
	if max < 0 {
		max = 0
	}
	count := (len(records) + perPage - 1) / perPage
	if count == 0 {
		count = 1
	}
	pages := make([]string, 0, count)
	for p := 0; p < count; p++ {
		start := p * perPage
		end := start + perPage
		if end > len(records) {
			end = len(records)
		}
		var b strings.Builder
		// Warm paper and ink/olive app palette.
		pdfFill(&b, "0.975 0.971 0.957", 0, 0, pageW, pageH)
		pdfFill(&b, "0.169 0.204 0.173", 0, 756, pageW, 86)
		// Brand emblem: open-book vector, and wordmark at top-right.
		pdfFill(&b, "0.928 0.941 0.910", 35, 775, 42, 42)
		pdfLine(&b, "0.169 0.204 0.173", 45, 802, 56, 806)
		pdfLine(&b, "0.169 0.204 0.173", 56, 806, 67, 802)
		pdfLine(&b, "0.169 0.204 0.173", 45, 802, 45, 784)
		pdfLine(&b, "0.169 0.204 0.173", 67, 802, 67, 784)
		pdfLine(&b, "0.169 0.204 0.173", 56, 806, 56, 784)
		pdfLine(&b, "0.169 0.204 0.173", 45, 784, 56, 780)
		pdfLine(&b, "0.169 0.204 0.173", 56, 780, 67, 784)
		b.WriteString("1 1 1 rg\n")
		pdfText(&b, 2, 18, 90, 794, "EduNexus")
		// Override white wordmark color for contrast via surrounding graphics state.
		pdfText(&b, 1, 9, 90, 778, "LEARNING, REIMAGINED")
		b.WriteString("0.16 0.19 0.16 rg\n")
		// Light watermark behind marks table, not obscuring text.
		b.WriteString("q 0.93 0.945 0.92 rg BT /F2 60 Tf 0.866 0.5 -0.5 0.866 92 302 Tm (EDUNEXUS) Tj ET Q\n")
		pdfText(&b, 2, 21, 35, 724, "EXAMINATION MARKSHEET")
		pdfFill(&b, "0.36 0.45 0.35", 35, 712, 68, 3)
		pdfText(&b, 1, 9, 35, 692, "COURSE NAME")
		pdfText(&b, 2, 12, 35, 675, truncateASCII(courseName, 65))
		pdfText(&b, 1, 9, 370, 692, "COURSE CODE")
		pdfText(&b, 2, 12, 370, 675, truncateASCII(courseCode, 21))
		pdfText(&b, 1, 9, 35, 649, "TEACHER")
		pdfText(&b, 2, 12, 35, 632, truncateASCII(teacherName, 64))
		pdfText(&b, 1, 9, 35, 609, "EXAMINATION")
		pdfText(&b, 2, 12, 35, 591, truncateASCII(examTitle, 78))
		pdfLine(&b, "0.84 0.85 0.81", 35, 579, 560, 579)
		pdfText(&b, 1, 9, 35, 560, "Published results  /  Total students: "+strconv.Itoa(len(records)))
		pdfText(&b, 1, 9, 370, 560, "Maximum marks: "+strconv.Itoa(max))
		// Table header.
		pdfFill(&b, "0.169 0.204 0.173", 35, 517, 525, 33)
		b.WriteString("1 1 1 rg\n")
		pdfText(&b, 2, 10, 49, 529, "NO.")
		pdfText(&b, 2, 10, 95, 529, "STUDENT ID / ROLL")
		pdfText(&b, 2, 10, 240, 529, "STUDENT NAME")
		pdfText(&b, 2, 10, 478, 529, "MARKS")
		// Body rows.
		for i, rec := range records[start:end] {
			y := 490 - i*15
			if i%2 == 0 {
				pdfFill(&b, "0.935 0.943 0.926", 35, y-6, 525, 17)
			} else {
				pdfFill(&b, "0.985 0.982 0.973", 35, y-6, 525, 17)
			}
			b.WriteString("0.16 0.19 0.16 rg\n")
			pdfText(&b, 1, 10, 49, y, strconv.Itoa(start+i+1))
			roll := rec.Roll
			if strings.TrimSpace(roll) == "" {
				roll = "Not set"
			}
			pdfText(&b, 2, 10, 95, y, truncateASCII(roll, 22))
			pdfText(&b, 1, 10, 240, y, truncateASCII(rec.Name, 37))
			pdfText(&b, 2, 10, 478, y, fmt.Sprintf("%d / %d", rec.Marks, max))
		}
		pdfLine(&b, "0.75 0.78 0.74", 35, 28, 560, 28)
		pdfText(&b, 1, 8, 35, 16, "Generated by EduNexus  |  Published totals only  |  Individual feedback is private")
		pdfText(&b, 1, 8, 515, 16, fmt.Sprintf("%d / %d", p+1, count))
		// Draw date discreetly.
		pdfText(&b, 1, 8, 478, 730, time.Now().Format("02 Jan 2006"))
		pages = append(pages, b.String())
	}
	// Assemble a minimal fully-compliant PDF with 2 standard Type1 fonts.
	var objects []string
	objects = append(objects, "<< /Type /Catalog /Pages 2 0 R >>")
	kids := make([]string, 0, len(pages))
	for p := range pages {
		kids = append(kids, fmt.Sprintf("%d 0 R", 5+p*2))
	}
	objects = append(objects, fmt.Sprintf("<< /Type /Pages /Kids [%s] /Count %d >>", strings.Join(kids, " "), len(pages)))
	objects = append(objects, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
	objects = append(objects, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>")
	for p, page := range pages {
		pageID := 5 + p*2
		streamID := pageID + 1
		objects = append(objects, fmt.Sprintf("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents %d 0 R >>", pageW, pageH, streamID))
		objects = append(objects, fmt.Sprintf("<< /Length %d >>\nstream\n%s\nendstream", len(page), page))
	}
	var pdf bytes.Buffer
	pdf.WriteString("%PDF-1.4\n")
	positions := []int{0}
	for i, o := range objects {
		positions = append(positions, pdf.Len())
		fmt.Fprintf(&pdf, "%d 0 obj\n%s\nendobj\n", i+1, o)
	}
	xref := pdf.Len()
	fmt.Fprintf(&pdf, "xref\n0 %d\n0000000000 65535 f \n", len(objects)+1)
	for _, pos := range positions[1:] {
		fmt.Fprintf(&pdf, "%010d 00000 n \n", pos)
	}
	fmt.Fprintf(&pdf, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF", len(objects)+1, xref)
	return pdf.Bytes()
}
